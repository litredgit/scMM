import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../src/features/analysis/results.contract.json', import.meta.url)
const target = new URL('../src/features/analysis/results.generated.ts', import.meta.url)
const contract = JSON.parse(readFileSync(source, 'utf8'))
const plots = new Set([
  ...Object.values(contract.operations).flatMap((operation) => operation.plots),
  ...Object.values(contract.resultPlots).flat(),
])
const names = [...plots].sort()
const contents = `// Generated by npm run generate:results from results.contract.json.\nexport type PlotKind =\n${names.map((name) => `  | '${name}'`).join('\n')}\n`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== contents) {
    throw new Error('Result types are out of date. Run npm run generate:results.')
  }
} else writeFileSync(target, contents)
