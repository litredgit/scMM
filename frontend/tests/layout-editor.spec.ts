import { test, expect, navigate } from './fixtures'
import { createProject, importDataset } from './support/project'
test('project home and read-only data editor use explicit sources and metadata', async ({
  page,
}) => {
  await page.goto('/')
  await expect(page.locator('.module-catalog')).toHaveCount(0)
  await importDataset(page, '只读矩阵编辑器')
  await navigate(page, '/data-check')
  await expect(page.getByRole('heading', { name: '数据检查', exact: true })).toBeVisible()
  await navigate(page, '/data-editor')
  const table = page
    .locator('section.card')
    .filter({ has: page.getByRole('heading', { name: '定量矩阵预览 · 只读' }) })
  await expect(table.locator('input')).toHaveCount(0)
  await expect(table.locator('tbody tr')).not.toHaveCount(0)
  const before = await table.locator('tbody').innerText()
  const group = page.locator('input[aria-label$=" group"]').first()
  await group.fill('人工分组')
  await page.getByRole('button', { name: '应用元数据', exact: true }).click()
  await expect(group).toHaveValue('人工分组')
  await expect.poll(() => table.locator('tbody').innerText()).toBe(before)
  const feature = page.locator('input[aria-label^="特征名称 "]').first()
  await feature.fill('审核名称')
  await page.getByRole('button', { name: '应用特征名称修改', exact: true }).click()
  await expect(feature).toHaveValue('审核名称')
  await expect.poll(() => table.locator('tbody').innerText()).toBe(before)
  await page.getByText('特征名称修改记录', { exact: true }).click()
  await expect(page.locator('pre').last()).toContainText('审核名称')
  await page.getByText('元数据修改记录', { exact: true }).click()
  await expect(page.locator('pre').first()).toContainText('人工分组')
  await expect
    .poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    .toBe(true)
})
test('preview parameters preserve precision and extraction rows allow batch edits', async ({
  page,
}) => {
  await createProject(page, '逐样本参数编辑')
  await page.getByRole('button', { name: '＋ 添加原始文件' }).click()
  await page.getByRole('button', { name: /extract.mzML/ }).click()
  await page.getByRole('button', { name: '添加 1 个文件', exact: true }).click()
  await navigate(page, '/raw')
  await page.getByRole('button', { name: '打开原始文件', exact: true }).click()
  if (
    !(await page
      .locator('summary')
      .filter({ hasText: /^细胞识别$/ })
      .evaluate((el) => (el.parentElement as HTMLDetailsElement).open))
  )
    await page
      .locator('summary')
      .filter({ hasText: /^细胞识别$/ })
      .click()
  for (const [key, value] of Object.entries({ ref_mz: '150', mz_min: '140', mz_max: '160' }))
    await page.getByLabel(key, { exact: true }).fill(value)
  const reference = page.getByLabel('ref_mz', { exact: true })
  const listId = await reference.getAttribute('list')
  expect(listId).toBeTruthy()
  const candidates = page.locator(`datalist[id="${listId}"] option`)
  await expect(candidates.first()).toBeAttached()
  const mass = (await candidates.first().getAttribute('value'))!
  await reference.fill(mass)
  await reference.blur()
  await expect(reference).toHaveValue(Number(mass).toFixed(4))
  await reference.fill('150')
  await reference.blur()
  await expect(page.getByText('使用所选参考离子', { exact: true })).toHaveCount(0)
  const signal = page.getByLabel('cell_min_signal', { exact: true })
  await expect(signal).toHaveValue('100000')
  await signal.fill('123456.789')
  await signal.blur()
  await expect(signal).toHaveValue('123456.789')
  await page.getByRole('button', { name: '应用参数', exact: true }).click()
  await navigate(page, '/extraction')
  await page.getByRole('button', { name: '检查参数与输入', exact: true }).click()
  const cell = page.locator('input[aria-label$=" cell_min_signal"]').first()
  await expect(cell).toHaveValue('123456.789')
  await cell.focus()
  await expect(cell).toHaveValue('123456.789')
  await cell.blur()
  await expect(page.locator('[aria-label$=" extraction_method"]')).toHaveCount(0)
  await expect(page.locator('[aria-label$=" ms_peak_snr_threshold"]')).toHaveValue('10')
  await expect(page.locator('[aria-label$=" feature_snr_threshold"]')).toHaveValue('3')
  await page.getByRole('button', { name: '按组对照', exact: true }).click()
  await expect(page.locator('.parameter-comparison tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: '逐样本编辑', exact: true }).click()
  await page.getByRole('button', { name: '应用全部样本参数', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
