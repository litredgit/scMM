export function displayName(value: unknown): string {
  const key = String(value ?? '')
  return names[key] ?? (/^scmm_|^(?:raw|original|feature_snr|X)$/.test(key) ? layerName(key) : key)
}
export function layerName(value: string) {
  if (['X', '当前 X'].includes(value)) return '当前矩阵'
  if (['raw', 'original', 'scmm_original'].includes(value)) return '原始强度'
  if (value === 'feature_snr') return '特征信噪比'
  const found = /^scmm_(.+)_(\d+)$/.exec(value)
  if (!found) return value
  const methods: Record<string, string> = {
    filter: '筛选',
    normalize: '归一化',
    impute: '插补',
    remove_outliers: '去异常',
    restore: '恢复',
  }
  return `${methods[found[1]!] ?? displayName(found[1]!)} ${Number(found[2]) + 1}`
}
